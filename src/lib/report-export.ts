function escapeHtml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function triggerDownload(filename: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.rel = "noopener";
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1500);
}

export function downloadReportPdf(report: RichGradeReport) {
  const html = reportHtmlDocument(report);
  const w = window.open("", "_blank", "noopener,noreferrer,width=900,height=1000");
  if (!w) {
    // Popup blocked — fall back to downloading an HTML report
    downloadReportFile(report, "html");
    return { mode: "file" as const };
  }
  w.document.open();
  w.document.write(html);
  w.document.close();
  // Give images a moment to paint, then open the print dialog (Save as PDF)
  window.setTimeout(() => {
    w.focus();
    w.print();
  }, 350);
  return { mode: "print" as const };
}

export function downloadReportFile(
  report: RichGradeReport,
  format: "html" | "json" = "html"
) {
  const base = `gemmint-${slugify(report.grade.name) || "report"}-${report.grade.id.slice(0, 8)}`;
  if (format === "json") {
    triggerDownload(
      `${base}.json`,
      new Blob([JSON.stringify(report, null, 2)], { type: "application/json" })
    );
    return;
  }
  triggerDownload(
    `${base}.html`,
    new Blob([reportHtmlDocument(report)], { type: "text/html;charset=utf-8" })
  );
}

export async function shareReport(report: RichGradeReport) {
  const url = reportShareUrl(report.grade.id);
  const title = `${report.grade.name} · GemMint Report`;
  const text = reportSummaryText(report);

  if (typeof navigator !== "undefined" && typeof navigator.share === "function") {
    try {
      await navigator.share({ title, text, url });
      return { mode: "native" as const };
    } catch (err) {
      // User cancelled share sheet
      if (err instanceof DOMException && err.name === "AbortError") {
        return { mode: "cancelled" as const };
      }
    }
  }

  await navigator.clipboard.writeText(`${text}\n${url}`);
  return { mode: "clipboard" as const };
}

export async function copyReportLink(grade: DashboardGrade | { id: string }) {
  const url = reportShareUrl(grade.id);
  await navigator.clipboard.writeText(url);
  return url;
}
