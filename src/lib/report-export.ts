function slugify(name: string) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 48);
}

export function reportShareUrl(gradeId: string) {
  if (typeof window === "undefined") {
    return `${SITE.url}/dashboard?report=${encodeURIComponent(gradeId)}`;
  }
  const url = new URL("/dashboard", window.location.origin);
  url.searchParams.set("report", gradeId);
  return url.toString();
}

export function reportSummaryText(report: RichGradeReport) {
  const g = report.grade;
  return [
    `${g.name} — GemMint AI Grade Report`,
    `${g.year} · ${g.set} · ${g.category}`,
    `PSA ${g.psa} · Beckett ${g.beckett} · ${g.confidence}% confidence`,
    `Est. value: $${g.estimatedValue.toLocaleString()}`,
    `Recommendation: ${g.recommendation}`,
    report.explanation,
    reportShareUrl(g.id),
  ].join("\n");
}

